def parse_multilabel(val: Union[str, List[str], None]) -> List[str]:
    if val is None:
        return []
    if isinstance(val, list):
        return [str(x).strip() for x in val if str(x).strip()]
    if isinstance(val, str):
        return [x.strip() for x in val.split(',') if x.strip()]
    return []

def parse_range(val: Union[str, float, None]) -> Optional[float]:
    """Преобразует '2-3' → 2.5, '3,5-4' → 3.75, '4' → 4.0"""
    if pd.isna(val):
        return None
    s = str(val).strip().replace(',', '.')
    if '-' in s:
        try:
            parts = s.split('-')
            return (float(parts[0]) + float(parts[1])) / 2
        except (ValueError, IndexError):
            return None
    try:
        return float(s)
    except ValueError:
        return None

def preprocess_input(raw_data: Dict[str, Union[str, float, List[str], None]], 
                     feature_names: List[str]) -> pd.DataFrame:
    """
    Превращает сырой JSON в DataFrame, готовый для модели.
    """
    result = {}
    
    result["Возраст"] = float(raw_data.get("Возраст")) if raw_data.get("Возраст") is not None else np.nan
    result["Способность пациента к ходьбе и бегу"] = MOBILITY_MAP.get(raw_data.get("Способность пациента к ходьбе и бегу"), np.nan)
    result["Баллы мускулатуры (верхние конечности)"] = parse_range(raw_data.get("Баллы мускулатуры (верхние конечности)"))
    result["Баллы мускулатуры (нижние конечности)"] = parse_range(raw_data.get("Баллы мускулатуры (нижние конечности)"))
    result["Применение миопатических приемов Говерса при вставании с пола (использование перекаты)"] = GOWERS_ROLL_MAP.get(raw_data.get("Применение миопатических приемов Говерса при вставании с пола (использование перекаты)"), np.nan)
    result["Применение миопатических приемов Говерса при вставании с пола (использование опоры)"] = GOWERS_SUPPORT_MAP.get(raw_data.get("Применение миопатических приемов Говерса при вставании с пола (использование опоры)"), np.nan)
    result["Тест с шестиминутной ходьбой"] = WALK_TEST_MAP.get(raw_data.get("Тест с шестиминутной ходьбой"))
    result["Приседания"] = SQUAT_MAP.get(raw_data.get("Приседания"))
    result["Подпрыгивания (вверх на 2-х ногах)"] = JUMP_2LEG_MAP.get(raw_data.get("Подпрыгивания (вверх на 2-х ногах)"), np.nan)
    result["Подпрыгивания (вверх на 1-ой ноге)"] = JUMP_1LEG_MAP.get(raw_data.get("Подпрыгивания (вверх на 1-ой ноге)"), np.nan)
    result["Ходьба по лестнице (подъем)"] = STAIR_UP_MAP.get(raw_data.get("Ходьба по лестнице (подъем)"), np.nan)
    result["Ходьба по лестнице (спуск)"] = STAIR_DOWN_MAP.get(raw_data.get("Ходьба по лестнице (спуск)"), np.nan)
    
    result["Особенности позы пациента, обусловленные контрактурами (функциональные нарушения верхней конечности)"] = UPPER_LIMBS_MAP.get(raw_data.get("Особенности позы пациента, обусловленные контрактурами (функциональные нарушения верхней конечности)"), np.nan)
    pos_raw = raw_data.get("Особенности позы пациента, обусловленные контрактурами (положение пациента)")
    result["Особенности позы пациента, обусловленные контрактурами (положение пациента)"] = POSITION_MAP.get(pos_raw, 1.0)
 
    result["Гиперлордоз"] = HYPERLORDOSIS_MAP.get(raw_data.get("Гиперлордоз"), 0)
    result["Сколиоз (стадии сколиоза по его выраженности)"] = SCOLIOSIS_STAGE_MAP.get(raw_data.get("Сколиоз (стадии сколиоза по его выраженности)"), 0)
    result["Сколиоз (спутники сколиотической деформации)"] = SCOLIOSIS_COMPANION_MAP.get(raw_data.get("Сколиоз (спутники сколиотической деформации)"), 0)
  
    contractures_list = parse_multilabel(raw_data.get("Тугоподвижность и контрактуры (нарушения суставной подвижности)"))
    cardio_list = parse_multilabel(raw_data.get("Кардиомиопатия"))
    
    df = pd.DataFrame([result])
    
    for col, val in zip(ALL_CONTRACTURES, mlb_contractures.transform([contractures_list])[0]):
        df[col] = int(val)
    for col, val in zip(ALL_CARDIO, mlb_cardio.transform([cardio_list])[0]):
        df[col] = int(val)
        
    cols_to_impute = [
        'Способность пациента к ходьбе и бегу',
        'Тест с шестиминутной ходьбой',
        'Приседания',
        'Подпрыгивания (вверх на 2-х ногах)',
        'Подпрыгивания (вверх на 1-ой ноге)',
        'Ходьба по лестнице (подъем)',
        'Ходьба по лестнице (спуск)'
    ]

    for col in cols_to_impute:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors='coerce')

    mobility_col = 'Способность пациента к ходьбе и бегу'
    if mobility_col in df.columns:
        mask_severe = df[mobility_col] >= 5
        mask_moderate = df[mobility_col] == 4

        # Стадии 5-6: пропуски = максимальная тяжесть
        severe_imputes = {
            'Тест с шестиминутной ходьбой': 0.0,
            'Ходьба по лестнице (подъем)': 5.0,
            'Ходьба по лестнице (спуск)': 5.0,
            'Подпрыгивания (вверх на 2-х ногах)': 5.0,
            'Подпрыгивания (вверх на 1-ой ноге)': 5.0,
            'Приседания': 5.0
        }
        for col, val in severe_imputes.items():
            if col in df.columns:
                df.loc[mask_severe & df[col].isna(), col] = val
        
        # Стадия 4: пропуски = предпоследний балл
        moderate_imputes = {
            'Подпрыгивания (вверх на 2-х ногах)': 4.0,
            'Подпрыгивания (вверх на 1-ой ноге)': 4.0
        }
        for col, val in moderate_imputes.items():
            if col in df.columns:
                df.loc[mask_moderate & df[col].isna(), col] = val

    # Статистическая импутация оставшихся пропусков медианами из обучения
    for col in df.columns:
        if df[col].isna().any() and col in MEDIANS:
            df[col] = df[col].fillna(MEDIANS[col])
        elif df[col].isna().any():
            df[col] = df[col].fillna(0)

    df = df.reindex(columns=feature_names, fill_value=0)
    
    return df